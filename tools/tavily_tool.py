from tavily import TavilyClient
import os
from dotenv import load_dotenv

load_dotenv()

client = TavilyClient(api_key=os.getenv("TAVILY_API_KEY"))

def tavily_search(query: str) -> str:
    """
    A tool that uses the Tavily API to generate a response based on the input query.

    Args:
        query (str): The input query to send to the Tavily API.

    Returns:
        str: The response generated by the Tavily API.
    """
    response = client.search(
        query = query,
        max_results = 5
        # include_sources = True
        )

    results = []

    for i,r in enumerate(response["results"], 1):
        title = r.get("title", "No title")
        url = r.get("url", "No URL")
        snippet = r.get("content", "").strip()

        if len(snippet) > 300:
            snippet = snippet[:200].rsplit(" ",1)[0] + "..."

        results.append(f"{i}. **{title}**\n {url}\n {snippet}\n")
    return "\n\n".join(results)
